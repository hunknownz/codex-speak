#!/usr/bin/env node
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  statSync,
  writeFileSync
} from "node:fs";
import path from "node:path";

const options = parseArgs(process.argv.slice(2));
const root = git(["rev-parse", "--show-toplevel"]);
process.chdir(root);

const outputDir = path.resolve(options.outputDir ?? "dist/qa-handoff");
const head = git(["rev-parse", "HEAD"]);
const version = readCargoVersion();
const packages = collectPackages();
const ciArtifacts = options.ciArtifactsJson
  ? collectCiArtifactsFromFile(options.ciArtifactsJson)
  : options.includeCiArtifacts
    ? await collectCiArtifacts()
    : [];
const coverage = describeCoverage(packages, ciArtifacts);

if (packages.length === 0 && ciArtifacts.length === 0) {
  fail(
    "No release packages or CI artifacts found. Build at least one package first, for example `./scripts/package-macos-release.sh`, or pass `--include-ci-artifacts` after the main CI succeeds."
  );
}

mkdirSync(outputDir, { recursive: true });
const handoff = {
  schemaVersion: 1,
  product: "codex-speak",
  version,
  git: {
    commit: head,
    describe: git(["describe", "--tags", "--always", "--dirty"], true) || head.slice(0, 7),
    dirty: git(["status", "--porcelain"]).length > 0
  },
  generatedAt: new Date().toISOString(),
  platformCoverage: coverage,
  packages,
  ciArtifacts,
  returnInstructions: {
    macos: "Return the entire codex-speak-macos-qa-* output directory generated by scripts/manual-qa-macos.sh.",
    windows: "Return the entire codex-speak-windows-qa-* output directory generated by scripts/manual-qa-windows.ps1."
  },
  reviewerCommands: {
    macos: "node scripts/check-manual-qa-report.mjs /path/to/codex-speak-macos-qa-*",
    windows: "node scripts/check-manual-qa-report.mjs C:\\path\\to\\codex-speak-windows-qa-*",
    releaseReadiness:
      "node scripts/check-release-readiness.mjs --require-manual-qa --macos-qa-dir /path/to/macos-qa --windows-qa-dir C:\\path\\to\\windows-qa"
  }
};

writeFileSync(
  path.join(outputDir, "qa-handoff.json"),
  `${JSON.stringify(handoff, null, 2)}\n`
);
writeFileSync(path.join(outputDir, "README.md"), renderReadme(handoff));

console.log(`Wrote QA handoff: ${outputDir}`);
for (const item of packages) {
  console.log(`${item.platform}: ${item.archive} ${item.sha256.slice(0, 12)}...`);
}
for (const item of ciArtifacts) {
  console.log(`ci artifact ${item.platform}: ${item.name} ${item.sizeBytes} bytes`);
}

function collectPackages() {
  const targets = [
    {
      platform: "macos",
      archive: "dist/codex-speak-macos.tar.gz",
      checksumFile: "dist/codex-speak-macos.tar.gz.sha256",
      packageDir: "dist/codex-speak-macos",
      manifestPath: "dist/codex-speak-macos/release-manifest.json",
      install: "./installers/install-macos.sh --skip-tts-download",
      qa: "./scripts/manual-qa-macos.sh --allow-missing-models"
    },
    {
      platform: "windows",
      archive: "dist/codex-speak-windows.zip",
      checksumFile: "dist/codex-speak-windows.zip.sha256",
      packageDir: "dist/codex-speak-windows",
      manifestPath: "dist/codex-speak-windows/release-manifest.json",
      install: ".\\installers\\install-windows.ps1 -SkipTtsDownload",
      qa: ".\\scripts\\manual-qa-windows.ps1 -AllowMissingModels"
    }
  ];

  const selected = options.platform === "all"
    ? targets
    : targets.filter((target) => target.platform === options.platform);

  return selected
    .filter((target) => {
      const present = existsSync(target.archive) && existsSync(target.manifestPath);
      if (!present && !options.allowMissing) {
        fail(`Missing ${target.platform} package or manifest. Expected ${target.archive} and ${target.manifestPath}.`);
      }
      return present;
    })
    .map((target) => describePackage(target));
}

function describePackage(target) {
  const manifest = readJson(target.manifestPath);
  const archiveSha = sha256(target.archive);
  const checksumSha = readChecksum(target.checksumFile);
  if (manifest.git?.commit !== head) {
    fail(
      `${target.platform} release manifest commit ${manifest.git?.commit ?? "missing"} does not match HEAD ${head}. Rebuild the package.`
    );
  }
  if (manifest.platform !== target.platform) {
    fail(`${target.platform} release manifest platform is ${manifest.platform ?? "missing"}.`);
  }
  if (manifest.git?.dirty !== false) {
    fail(`${target.platform} release manifest was generated from a dirty worktree. Rebuild from a clean commit.`);
  }
  if (checksumSha !== archiveSha) {
    fail(
      `${target.platform} checksum file ${target.checksumFile} does not match ${target.archive}. Expected ${archiveSha}, found ${checksumSha}.`
    );
  }

  return {
    platform: target.platform,
    archive: target.archive,
    archiveBytes: statSync(target.archive).size,
    sha256: archiveSha,
    checksumFile: target.checksumFile,
    packageDir: target.packageDir,
    manifest: {
      path: target.manifestPath,
      version: manifest.version,
      gitCommit: manifest.git.commit,
      verification: manifest.verification
    },
    testerCommands: {
      install: target.install,
      verifyPackage: manifest.verification?.verifyManifest,
      verifyInstall: manifest.verification?.verifyInstall,
      verifyCodex: manifest.verification?.verifyCodex,
      verifyControls: manifest.verification?.verifyControls,
      manualQa: target.qa
    }
  };
}

async function collectCiArtifacts() {
  const repo = parseGitHubRepo(git(["remote", "get-url", "origin"]));
  if (!repo) {
    fail("Could not parse GitHub origin remote; CI artifacts require a github.com origin.");
  }

  const runs = await githubJson(repo, `/repos/${repo}/actions/runs?per_page=50`);
  const run = runs.workflow_runs?.find((item) =>
    item.name === "CI" && item.head_sha === head && item.conclusion === "success"
  );
  if (!run) {
    fail(`No successful CI run found for HEAD ${head}. Push main and wait for CI before using --include-ci-artifacts.`);
  }

  const artifacts = await githubJson(repo, `/repos/${repo}/actions/runs/${run.id}/artifacts?per_page=100`);
  const requiredPlatforms = options.platform === "all" ? ["macos", "windows"] : [options.platform];
  return requiredPlatforms.map((platform) => {
    const name = `codex-speak-${platform}-ci`;
    const artifact = artifacts.artifacts?.find((item) => item.name === name);
    if (!artifact || artifact.expired || artifact.size_in_bytes <= 0) {
      fail(`${name} CI artifact is missing, expired, or empty for run ${run.html_url}.`);
    }
    return normalizeCiArtifact({
      platform,
      name,
      sizeBytes: artifact.size_in_bytes,
      expired: artifact.expired,
      runId: run.id,
      runUrl: run.html_url,
      downloadApiUrl: artifact.archive_download_url
    });
  });
}

function collectCiArtifactsFromFile(inputPath) {
  const resolved = path.resolve(inputPath);
  if (!existsSync(resolved) || !statSync(resolved).isFile()) {
    fail(`CI artifact JSON file not found: ${inputPath}`);
  }
  const raw = readJson(resolved);
  const artifacts = Array.isArray(raw) ? raw : raw.artifacts;
  if (!Array.isArray(artifacts)) {
    fail(`CI artifact JSON must be an array or an object with an artifacts array: ${inputPath}`);
  }
  const normalized = artifacts.map((item) =>
    normalizeCiArtifact({
      platform: item.platform,
      name: item.name,
      sizeBytes: item.sizeBytes ?? item.size_in_bytes,
      expired: item.expired ?? false,
      runId: item.runId ?? raw.runId,
      runUrl: item.runUrl ?? raw.runUrl,
      downloadApiUrl: item.downloadApiUrl ?? item.archive_download_url
    })
  );
  const requiredPlatforms = options.platform === "all" ? ["macos", "windows"] : [options.platform];
  for (const platform of requiredPlatforms) {
    const expectedName = `codex-speak-${platform}-ci`;
    if (!normalized.some((item) => item.platform === platform && item.name === expectedName)) {
      fail(`CI artifact JSON is missing ${expectedName}.`);
    }
  }
  return normalized.filter((item) => requiredPlatforms.includes(item.platform));
}

function normalizeCiArtifact(item) {
  if (!["macos", "windows"].includes(item.platform)) {
    fail(`CI artifact platform must be macos or windows: ${item.platform ?? "missing"}`);
  }
  const expectedName = `codex-speak-${item.platform}-ci`;
  if (item.name !== expectedName) {
    fail(`CI artifact for ${item.platform} must be named ${expectedName}, found ${item.name ?? "missing"}.`);
  }
  const sizeBytes = Number(item.sizeBytes);
  if (!Number.isFinite(sizeBytes) || sizeBytes <= 0) {
    fail(`CI artifact ${item.name} must have a positive sizeBytes value.`);
  }
  if (item.expired) {
    fail(`CI artifact ${item.name} is expired.`);
  }
  if (!item.runUrl || !/^https:\/\/github\.com\//.test(item.runUrl)) {
    fail(`CI artifact ${item.name} must include a GitHub runUrl.`);
  }
  if (!item.downloadApiUrl || !/^https:\/\/api\.github\.com\//.test(item.downloadApiUrl)) {
    fail(`CI artifact ${item.name} must include a GitHub downloadApiUrl.`);
  }
  return {
    platform: item.platform,
    name: item.name,
    sizeBytes,
    expired: false,
    runId: item.runId ?? null,
    runUrl: item.runUrl,
    downloadApiUrl: item.downloadApiUrl
  };
}

function renderReadme(handoff) {
  const macos = handoff.packages.find((item) => item.platform === "macos");
  const windows = handoff.packages.find((item) => item.platform === "windows");
  const targetLabel = handoff.packages.length
    ? handoff.packages.map((item) => displayPlatform(item.platform)).join(" and ")
    : "CI artifact";
  const ciArtifactSection = renderCiArtifacts(handoff.ciArtifacts ?? []);
  const distributionSentence = renderDistributionSentence(handoff.packages, handoff.ciArtifacts ?? []);
  const packageList = handoff.packages.length
    ? handoff.packages
        .map(
          (item) => `- ${displayPlatform(item.platform)}: \`${item.archive}\`
  - sha256: \`${item.sha256}\`
  - manifest: \`${item.manifest.path}\``
        )
        .join("\n")
    : "No local release archive was included. Use the CI artifact metadata above to download a smoke package from GitHub Actions.";
  return `# Codex Speak External QA Handoff

Version: ${handoff.version}
Commit: ${handoff.git.commit}
Generated: ${handoff.generatedAt}

${renderCoverageNotice(handoff.platformCoverage)}

This folder is a checklist for external ${targetLabel} testers. ${distributionSentence}

${ciArtifactSection}

## Packages

${packageList}

## macOS Tester Steps

${macos ? renderMacosSteps(macos) : renderMissingPackageSteps("macos", handoff.ciArtifacts ?? [])}

## Windows Tester Steps

${windows ? renderWindowsSteps(windows) : renderMissingPackageSteps("windows", handoff.ciArtifacts ?? [])}

## What Testers Return

${renderReturnInstructions(macos, windows, handoff.ciArtifacts ?? [])}
- If a sound, app, install step, pronunciation dictionary control, or mixed Chinese/English pronunciation check fails, include a short note describing what was seen or heard.

## Reviewer Checks

${renderReviewerChecks(macos, windows, handoff.ciArtifacts ?? [])}
`;
}

function renderDistributionSentence(packages, artifacts) {
  if (packages.length && artifacts.length) {
    return "Send each included local release archive and its .sha256 file when present, or use the CI artifact links below for platforms not built locally.";
  }
  if (packages.length) {
    return "Send each included release archive, its .sha256 file when present, and these instructions to the matching tester.";
  }
  return "Use the CI artifact links below to download the smoke package for each tester, then send these instructions with the downloaded archive contents.";
}

function renderCiArtifacts(artifacts) {
  if (!artifacts.length) {
    return `## CI Artifacts

No CI artifacts were included. Run \`node scripts/prepare-qa-handoff.mjs --allow-missing --include-ci-artifacts\` to attach the latest successful main CI smoke package artifact metadata for this commit.`;
  }

  return `## CI Artifacts

These artifacts come from the latest successful main CI run for this exact commit. They are useful for external QA before a formal release tag exists, especially when the local machine cannot build the Windows package.

Run: ${artifacts[0].runUrl}

${artifacts
  .map(
    (item) => `- ${displayPlatform(item.platform)}: \`${item.name}\`
  - size: ${item.sizeBytes} bytes
  - artifact page/API: ${item.downloadApiUrl}`
  )
  .join("\n")}

If downloading from the GitHub UI, open the run URL and use the Artifacts section. If downloading through the API, use a GitHub token with Actions artifact access.

GitHub downloads each artifact as a zip file. Unzip that artifact first; inside it you should find the platform release archive and its .sha256 file. Then follow the matching tester steps below or in \`docs/release-qa.md\`.

${renderCiArtifactSteps(artifacts)}`;
}

function renderCiArtifactSteps(artifacts) {
  const lines = [];
  if (artifacts.some((item) => item.platform === "macos")) {
    lines.push(`macOS artifact quick path:

\`\`\`bash
unzip codex-speak-macos-ci.zip
shasum -a 256 -c codex-speak-macos.tar.gz.sha256
tar -xzf codex-speak-macos.tar.gz
cd codex-speak-macos
./bin/codex-speak verify-package --package-dir .
./installers/install-macos.sh --skip-tts-download
./scripts/manual-qa-macos.sh --allow-missing-models
\`\`\``);
  }
  if (artifacts.some((item) => item.platform === "windows")) {
    lines.push(`Windows artifact quick path:

\`\`\`powershell
Expand-Archive -Force .\\codex-speak-windows-ci.zip .
$Expected = ((Get-Content .\\codex-speak-windows.zip.sha256 -Raw) -split '\\s+')[0].ToLowerInvariant()
$Actual = (Get-FileHash .\\codex-speak-windows.zip -Algorithm SHA256).Hash.ToLowerInvariant()
if ($Actual -ne $Expected) { throw "sha256 mismatch: expected $Expected but got $Actual" }
Expand-Archive -Force .\\codex-speak-windows.zip .
cd .\\codex-speak-windows
.\\bin\\codex-speak.exe verify-package --package-dir .
.\\installers\\install-windows.ps1 -SkipTtsDownload
.\\scripts\\manual-qa-windows.ps1 -AllowMissingModels
\`\`\``);
  }
  return lines.join("\n\n");
}

function describeCoverage(packages, artifacts = []) {
  const required = ["macos", "windows"];
  const included = Array.from(new Set([
    ...packages.map((item) => item.platform),
    ...artifacts.map((item) => item.platform)
  ]));
  const missing = required.filter((platform) => !included.includes(platform));
  return {
    required,
    included,
    missing,
    complete: missing.length === 0
  };
}

function renderMissingPackageSteps(platform, artifacts) {
  if (artifacts.some((item) => item.platform === platform)) {
    return `No local ${displayPlatform(platform)} package was included in this handoff. Use the ${displayPlatform(platform)} CI artifact quick path above.`;
  }
  return `No ${displayPlatform(platform)} package or CI artifact was included in this handoff.`;
}

function renderCoverageNotice(coverage) {
  if (coverage.complete) {
    return "Coverage: complete macOS and Windows QA handoff.";
  }
  const included = coverage.included.map(displayPlatform).join(" and ") || "none";
  const missing = coverage.missing.map(displayPlatform).join(" and ");
  return `Coverage: partial handoff. Included: ${included}. Missing: ${missing}. This is useful for platform-specific QA, but final release readiness still needs both macOS and Windows QA evidence.`;
}

function renderReturnInstructions(macos, windows, artifacts = []) {
  const lines = [];
  if (macos || artifacts.some((item) => item.platform === "macos")) {
    lines.push("- macOS: the entire `codex-speak-macos-qa-*` output directory.");
  }
  if (windows || artifacts.some((item) => item.platform === "windows")) {
    lines.push("- Windows: the entire `codex-speak-windows-qa-*` output directory.");
  }
  return lines.join("\n");
}

function renderReviewerChecks(macos, windows, artifacts = []) {
  const commands = [];
  const hasMacos = Boolean(macos) || artifacts.some((item) => item.platform === "macos");
  const hasWindows = Boolean(windows) || artifacts.some((item) => item.platform === "windows");
  if (hasMacos) {
    commands.push("node scripts/check-manual-qa-report.mjs /path/to/codex-speak-macos-qa-*");
  }
  if (hasWindows) {
    commands.push("node scripts/check-manual-qa-report.mjs /path/to/codex-speak-windows-qa-*");
  }
  if (hasMacos && hasWindows) {
    commands.push(
      "node scripts/check-release-readiness.mjs --require-manual-qa --macos-qa-dir /path/to/macos-qa --windows-qa-dir C:\\path\\to\\windows-qa"
    );
  } else {
    commands.push("# Final release readiness still needs both macOS and Windows QA directories.");
  }
  return `\`\`\`bash\n${commands.join("\n")}\n\`\`\``;
}

