function displayPlatform(platform) {
  return platform === "macos" ? "macOS" : platform === "windows" ? "Windows" : platform;
}

function parseArgs(args) {
  const result = {
    platform: "all",
    outputDir: null,
    allowMissing: false,
    includeCiArtifacts: false,
    ciArtifactsJson: null
  };
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--platform") {
      result.platform = args[++index];
    } else if (arg === "--output-dir") {
      result.outputDir = args[++index];
    } else if (arg === "--allow-missing") {
      result.allowMissing = true;
    } else if (arg === "--include-ci-artifacts") {
      result.includeCiArtifacts = true;
    } else if (arg === "--ci-artifacts-json") {
      result.ciArtifactsJson = args[++index];
      if (!result.ciArtifactsJson) {
        fail("--ci-artifacts-json requires a file path");
      }
    } else if (arg === "--help" || arg === "-h") {
      printUsage();
      process.exit(0);
    } else {
      fail(`Unknown option: ${arg}`);
    }
  }
  if (!["all", "macos", "windows"].includes(result.platform)) {
    fail("--platform must be one of: all, macos, windows");
  }
  return result;
}

function printUsage() {
  console.log(`Usage: node scripts/prepare-qa-handoff.mjs [options]

Options:
  --platform <all|macos|windows>  Package set to include. Default: all.
  --output-dir <dir>              Output directory. Default: dist/qa-handoff.
  --allow-missing                 Include only package directories that exist.
  --include-ci-artifacts          Attach latest successful main CI smoke artifact metadata for this commit.
                                  Set GITHUB_TOKEN if GitHub API rate limiting or private artifact access applies.
  --ci-artifacts-json <file>      Attach CI artifact metadata from a local JSON file instead of querying GitHub.
  --help                          Show this help.

Examples:
  node scripts/prepare-qa-handoff.mjs --allow-missing
  node scripts/prepare-qa-handoff.mjs --allow-missing --include-ci-artifacts
  node scripts/prepare-qa-handoff.mjs --platform windows --allow-missing --ci-artifacts-json tests/fixtures/ci-artifacts.json
  node scripts/prepare-qa-handoff.mjs --platform macos
`);
}

function readCargoVersion() {
  const raw = readFileSync("Cargo.toml", "utf8");
  const match = raw.match(/^version\s*=\s*"([^"]+)"/m);
  if (!match) fail("Could not read package version from Cargo.toml");
  return match[1];
}

function readJson(file) {
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    fail(`Could not parse ${file}: ${error.message}`);
  }
}

function readChecksum(file) {
  if (!existsSync(file) || !statSync(file).isFile()) {
    fail(`Missing checksum file: ${file}`);
  }
  const raw = readFileSync(file, "utf8").trim();
  const match = raw.match(/^([a-fA-F0-9]{64})(?:\s+|$)/);
  if (!match) {
    fail(`Invalid checksum file: ${file}`);
  }
  return match[1].toLowerCase();
}

function sha256(file) {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

async function githubJson(repo, apiPath) {
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": "codex-speak-qa-handoff"
  };
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }
  const response = await fetch(`https://api.github.com${apiPath}`, { headers });
  const body = await response.text();
  let json;
  try {
    json = JSON.parse(body);
  } catch {
    fail(`GitHub API returned non-JSON for ${repo}: ${body.slice(0, 120)}`);
  }
  if (!response.ok) {
    const tokenHint = response.status === 403
      ? " Set GITHUB_TOKEN to a GitHub token with Actions artifact access and retry."
      : "";
    fail(`GitHub API ${response.status} for ${repo}: ${json.message ?? body}${tokenHint}`);
  }
  return json;
}

function parseGitHubRepo(remote) {
  const ssh = remote.match(/^git@github\.com:([^/]+\/[^/]+?)(?:\.git)?$/);
  if (ssh) return ssh[1];
  const https = remote.match(/^https:\/\/github\.com\/([^/]+\/[^/]+?)(?:\.git)?$/);
  if (https) return https[1];
  return null;
}

function git(args, optional = false) {
  try {
    return execFileSync("git", args, { encoding: "utf8" }).trim();
  } catch (error) {
    if (optional) return "";
    throw error;
  }
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
