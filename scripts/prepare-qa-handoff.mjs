#!/usr/bin/env node
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  statSync,
  writeFileSync
} from "node:fs";
import path from "node:path";

const options = parseArgs(process.argv.slice(2));
const root = git(["rev-parse", "--show-toplevel"]);
process.chdir(root);

const outputDir = path.resolve(options.outputDir ?? "dist/qa-handoff");
const head = git(["rev-parse", "HEAD"]);
const version = readCargoVersion();
const packages = collectPackages();

if (packages.length === 0) {
  fail(
    "No release packages found. Build at least one package first, for example `./scripts/package-macos-release.sh`."
  );
}

mkdirSync(outputDir, { recursive: true });
const handoff = {
  schemaVersion: 1,
  product: "codex-speak",
  version,
  git: {
    commit: head,
    describe: git(["describe", "--tags", "--always", "--dirty"], true) || head.slice(0, 7),
    dirty: git(["status", "--porcelain"]).length > 0
  },
  generatedAt: new Date().toISOString(),
  packages,
  returnInstructions: {
    macos: "Return the entire codex-speak-macos-qa-* output directory generated by scripts/manual-qa-macos.sh.",
    windows: "Return the entire codex-speak-windows-qa-* output directory generated by scripts/manual-qa-windows.ps1."
  },
  reviewerCommands: {
    macos: "node scripts/check-manual-qa-report.mjs /path/to/codex-speak-macos-qa-*",
    windows: "node scripts/check-manual-qa-report.mjs C:\\path\\to\\codex-speak-windows-qa-*",
    releaseReadiness:
      "node scripts/check-release-readiness.mjs --require-manual-qa --macos-qa-dir /path/to/macos-qa --windows-qa-dir C:\\path\\to\\windows-qa"
  }
};

writeFileSync(
  path.join(outputDir, "qa-handoff.json"),
  `${JSON.stringify(handoff, null, 2)}\n`
);
writeFileSync(path.join(outputDir, "README.md"), renderReadme(handoff));

console.log(`Wrote QA handoff: ${outputDir}`);
for (const item of packages) {
  console.log(`${item.platform}: ${item.archive} ${item.sha256.slice(0, 12)}...`);
}

function collectPackages() {
  const targets = [
    {
      platform: "macos",
      archive: "dist/codex-speak-macos.tar.gz",
      checksumFile: "dist/codex-speak-macos.tar.gz.sha256",
      packageDir: "dist/codex-speak-macos",
      manifestPath: "dist/codex-speak-macos/release-manifest.json",
      install: "./installers/install-macos.sh --skip-tts-download",
      qa: "./scripts/manual-qa-macos.sh --allow-missing-models"
    },
    {
      platform: "windows",
      archive: "dist/codex-speak-windows.zip",
      checksumFile: "dist/codex-speak-windows.zip.sha256",
      packageDir: "dist/codex-speak-windows",
      manifestPath: "dist/codex-speak-windows/release-manifest.json",
      install: ".\\installers\\install-windows.ps1 -SkipTtsDownload",
      qa: ".\\scripts\\manual-qa-windows.ps1 -AllowMissingModels"
    }
  ];

  const selected = options.platform === "all"
    ? targets
    : targets.filter((target) => target.platform === options.platform);

  return selected
    .filter((target) => {
      const present = existsSync(target.archive) && existsSync(target.manifestPath);
      if (!present && !options.allowMissing) {
        fail(`Missing ${target.platform} package or manifest. Expected ${target.archive} and ${target.manifestPath}.`);
      }
      return present;
    })
    .map((target) => describePackage(target));
}

function describePackage(target) {
  const manifest = readJson(target.manifestPath);
  if (manifest.git?.commit !== head) {
    fail(
      `${target.platform} release manifest commit ${manifest.git?.commit ?? "missing"} does not match HEAD ${head}. Rebuild the package.`
    );
  }
  if (manifest.platform !== target.platform) {
    fail(`${target.platform} release manifest platform is ${manifest.platform ?? "missing"}.`);
  }

  return {
    platform: target.platform,
    archive: target.archive,
    archiveBytes: statSync(target.archive).size,
    sha256: sha256(target.archive),
    checksumFile: existsSync(target.checksumFile) ? target.checksumFile : null,
    packageDir: target.packageDir,
    manifest: {
      path: target.manifestPath,
      version: manifest.version,
      gitCommit: manifest.git.commit,
      verification: manifest.verification
    },
    testerCommands: {
      install: target.install,
      verifyPackage: manifest.verification?.verifyManifest,
      verifyInstall: manifest.verification?.verifyInstall,
      verifyCodex: manifest.verification?.verifyCodex,
      verifyControls: manifest.verification?.verifyControls,
      manualQa: target.qa
    }
  };
}

function renderReadme(handoff) {
  const macos = handoff.packages.find((item) => item.platform === "macos");
  const windows = handoff.packages.find((item) => item.platform === "windows");
  const targetLabel = handoff.packages.map((item) => displayPlatform(item.platform)).join(" and ");
  return `# Codex Speak External QA Handoff

Version: ${handoff.version}
Commit: ${handoff.git.commit}
Generated: ${handoff.generatedAt}

This folder is a checklist for external ${targetLabel} testers. Send each release archive, its .sha256 file when present, and these instructions to the matching tester.

## Packages

${handoff.packages
  .map(
    (item) => `- ${displayPlatform(item.platform)}: \`${item.archive}\`
  - sha256: \`${item.sha256}\`
  - manifest: \`${item.manifest.path}\``
  )
  .join("\n")}

## macOS Tester Steps

${macos ? renderMacosSteps(macos) : "No macOS package was included in this handoff."}

## Windows Tester Steps

${windows ? renderWindowsSteps(windows) : "No Windows package was included in this handoff."}

## What Testers Return

${renderReturnInstructions(macos, windows)}
- If a sound, app, install step, pronunciation dictionary control, or mixed Chinese/English pronunciation check fails, include a short note describing what was seen or heard.

## Reviewer Checks

${renderReviewerChecks(macos, windows)}
`;
}

function renderReturnInstructions(macos, windows) {
  const lines = [];
  if (macos) lines.push("- macOS: the entire `codex-speak-macos-qa-*` output directory.");
  if (windows) lines.push("- Windows: the entire `codex-speak-windows-qa-*` output directory.");
  return lines.join("\n");
}

function renderReviewerChecks(macos, windows) {
  const commands = [];
  if (macos) {
    commands.push("node scripts/check-manual-qa-report.mjs /path/to/codex-speak-macos-qa-*");
  }
  if (windows) {
    commands.push("node scripts/check-manual-qa-report.mjs /path/to/codex-speak-windows-qa-*");
  }
  if (macos && windows) {
    commands.push(
      "node scripts/check-release-readiness.mjs --require-manual-qa --macos-qa-dir /path/to/macos-qa --windows-qa-dir C:\\path\\to\\windows-qa"
    );
  } else {
    commands.push("# Final release readiness still needs both macOS and Windows QA directories.");
  }
  return `\`\`\`bash\n${commands.join("\n")}\n\`\`\``;
}

function renderMacosSteps(item) {
  return `\`\`\`bash
shasum -a 256 -c ${path.basename(item.checksumFile ?? `${item.archive}.sha256`)}
tar -xzf ${path.basename(item.archive)}
cd codex-speak-macos
${item.testerCommands.verifyPackage}
${item.testerCommands.install}
${item.testerCommands.verifyInstall}
${item.testerCommands.verifyCodex}
${item.testerCommands.verifyControls}
${item.testerCommands.manualQa}
\`\`\`

During manual QA, confirm the control app opens, child mode and voice settings can change, one pronunciation dictionary rule can be added, previewed, and deleted, speech is audible, mixed Chinese/English speech does not spell technical words letter by letter, stop works, and the pet has no solid background block.`;
}

function renderWindowsSteps(item) {
  return `\`\`\`powershell
Get-FileHash .\\${path.basename(item.archive)} -Algorithm SHA256
Get-Content .\\${path.basename(item.checksumFile ?? `${item.archive}.sha256`)}
Expand-Archive -Force .\\${path.basename(item.archive)} .
cd .\\codex-speak-windows
${item.testerCommands.verifyPackage}
${item.testerCommands.install}
${item.testerCommands.verifyInstall}
${item.testerCommands.verifyCodex}
${item.testerCommands.verifyControls}
${item.testerCommands.manualQa}
\`\`\`

During manual QA, confirm the control app opens, child mode and voice settings can change, one pronunciation dictionary rule can be added, previewed, and deleted, speech is audible, mixed Chinese/English speech does not spell technical words letter by letter, stop works, and no lingering playback process remains.`;
}

function displayPlatform(platform) {
  return platform === "macos" ? "macOS" : platform === "windows" ? "Windows" : platform;
}

function parseArgs(args) {
  const result = {
    platform: "all",
    outputDir: null,
    allowMissing: false
  };
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--platform") {
      result.platform = args[++index];
    } else if (arg === "--output-dir") {
      result.outputDir = args[++index];
    } else if (arg === "--allow-missing") {
      result.allowMissing = true;
    } else if (arg === "--help" || arg === "-h") {
      printUsage();
      process.exit(0);
    } else {
      fail(`Unknown option: ${arg}`);
    }
  }
  if (!["all", "macos", "windows"].includes(result.platform)) {
    fail("--platform must be one of: all, macos, windows");
  }
  return result;
}

function printUsage() {
  console.log(`Usage: node scripts/prepare-qa-handoff.mjs [options]

Options:
  --platform <all|macos|windows>  Package set to include. Default: all.
  --output-dir <dir>              Output directory. Default: dist/qa-handoff.
  --allow-missing                 Include only package directories that exist.
  --help                          Show this help.

Examples:
  node scripts/prepare-qa-handoff.mjs --allow-missing
  node scripts/prepare-qa-handoff.mjs --platform macos
`);
}

function readCargoVersion() {
  const raw = readFileSync("Cargo.toml", "utf8");
  const match = raw.match(/^version\s*=\s*"([^"]+)"/m);
  if (!match) fail("Could not read package version from Cargo.toml");
  return match[1];
}

function readJson(file) {
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    fail(`Could not parse ${file}: ${error.message}`);
  }
}

function sha256(file) {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

function git(args, optional = false) {
  try {
    return execFileSync("git", args, { encoding: "utf8" }).trim();
  } catch (error) {
    if (optional) return "";
    throw error;
  }
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
